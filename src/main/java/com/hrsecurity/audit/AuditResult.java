package com.hrsecurity.audit;

/**
 * 审计结果：成功 / 失败。
 *
 * 为什么失败也要记（这是本模块的一个明确取舍）：
 * - 安全审计关心的不只是"谁看了数据"，还包括"谁**试图**看数据"——
 *   反复刷无权限接口、拿别人的 id 试探，这类行为只有在失败记录里才看得见；
 * - 失败记录同时是排障线索（"这次运维动作没生效，因为工号对不上"）；
 * - 代价：会多写一行（异步写入，对主流程无影响）。
 *
 * 说明：被 Spring Security 在**方法执行前**拦下的越权（403）不会进入切面，
 * 因此这里没有"DENIED"状态——那种尝试发生在业务方法之外，见 docs/audit-design.md 的"未覆盖范围"。
 */
public enum AuditResult {

    /** 业务方法正常返回 */
    SUCCESS,

    /** 业务方法抛异常（含业务校验失败、数据异常） */
    FAILURE
}
